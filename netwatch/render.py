"""Self-contained HTML report.

One file you can email. The CSS, the JavaScript and the report data are inlined,
so it opens from a file system with no server and no network. The same static
assets drive the live dashboard and the hosted demo, so there is one UI to keep
correct rather than three.
"""

from __future__ import annotations

import json
from pathlib import Path

__all__ = ["render_html", "static_dir", "read_asset"]

_STATIC = Path(__file__).parent / "static"


def static_dir() -> Path:
    return _STATIC


def read_asset(name: str) -> str:
    return (_STATIC / name).read_text(encoding="utf-8")


def _safe_json(data: object) -> str:
    """JSON that cannot terminate or escape the script element it sits inside.

    Escaping ``<``, ``>`` and ``&`` as unicode escapes is the standard way to
    embed JSON in HTML. It leaves the value identical to ``json.loads`` while
    making it impossible for a string in the report - a DNS name, a Host
    header - to close the script block or open a tag.
    """
    encoded = json.dumps(data, ensure_ascii=False, indent=None, separators=(",", ":"))
    return (
        encoded.replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("&", "\\u0026")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def render_html(report: dict[str, object], *, title: str | None = None) -> str:
    """Return a complete standalone HTML document for one report."""
    capture_name = str((report.get("capture") or {}).get("name") or "capture")
    page_title = title or f"NetWatch - {capture_name}"
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{_html_escape(page_title)}</title>
<meta name="description" content="Network telemetry and anomaly detection report generated by NetWatch.">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16'%3E%3Crect width='16' height='16' rx='3' fill='%230b0f14'/%3E%3Cpath d='M2 9h2.5l1.2-4 2 7 1.8-5 1.2 2H14' fill='none' stroke='%2337d399' stroke-width='1.4' stroke-linecap='round' stroke-linejoin='round'/%3E%3C/svg%3E">
<style>
{read_asset('style.css')}
</style>
</head>
<body>
<main class="wrap" id="app">
  <div class="note">Loading report.</div>
</main>
<script>window.__NETWATCH_REPORT__ = {_safe_json(report)};</script>
<script>
{read_asset('app.js')}
</script>
</body>
</html>
"""


def _html_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )
