"""Shared helpers for the test suite.

The fixtures are regenerated by the same code that ships in the package, and
the tests assert that the committed bytes still match what the generator
produces. A fixture that quietly drifts away from the generator would make
every rule test meaningless.
"""

from __future__ import annotations

import functools
import json
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = Path(__file__).resolve().parent / "fixtures"

# The generator's default start instant. Fixed on purpose: the committed
# fixtures and the demo report must be byte-reproducible.
START_NS = 1_760_000_000_000_000_000
SEED = 7


def pcap_bytes(records, *, endian: str = "<", nsec: bool = False, linktype: int = 1) -> bytes:
    """Build a classic pcap file by hand, for reader tests."""
    magic = 0xA1B23C4D if nsec else 0xA1B2C3D4
    out = struct.pack(endian + "IHHiIII", magic, 2, 4, 0, 0, 65535, linktype)
    for ts_ns, data in records:
        seconds, remainder = divmod(ts_ns, 1_000_000_000)
        fraction = remainder if nsec else remainder // 1_000
        out += struct.pack(endian + "IIII", seconds, fraction, len(data), len(data)) + data
    return out


def pcapng_block(block_type: int, body: bytes = b"", *, endian: str = "<") -> bytes:
    padding = (-len(body)) % 4
    body = body + b"\x00" * padding
    total = 12 + len(body)
    return (
        struct.pack(endian + "II", block_type, total)
        + body
        + struct.pack(endian + "I", total)
    )


def pcapng_section(*, endian: str = "<") -> bytes:
    body = struct.pack(endian + "IHHq", 0x1A2B3C4D, 1, 0, -1)
    body += struct.pack(endian + "HH", 0, 0)  # opt_endofopt
    return pcapng_block(0x0A0D0D0A, body, endian=endian)


def pcapng_interface(*, endian: str = "<", linktype: int = 1, tsresol: int | None = None) -> bytes:
    body = struct.pack(endian + "HHI", linktype, 0, 262144)
    if tsresol is not None:
        body += struct.pack(endian + "HH", 9, 1) + bytes([tsresol]) + b"\x00" * 3
    body += struct.pack(endian + "HH", 0, 0)
    return pcapng_block(1, body, endian=endian)


def pcapng_epb(data: bytes, ts_ns: int, *, endian: str = "<", iface: int = 0, tsresol: int = 6) -> bytes:
    """Enhanced Packet Block.

    ``tsresol`` is the interface's decimal timestamp resolution exponent: 6 for
    microseconds (the pcapng default), 9 for nanoseconds. The stored value is
    in those units, so the timestamp has to be divided before it is written.
    """
    raw = ts_ns // (10 ** (9 - tsresol))
    high = (raw >> 32) & 0xFFFFFFFF
    low = raw & 0xFFFFFFFF
    body = struct.pack(endian + "IIIII", iface, high, low, len(data), len(data)) + data
    return pcapng_block(6, body, endian=endian)


@functools.lru_cache(maxsize=32)
def report_for(scenario: str, with_baseline: bool = True) -> dict:
    """Analyze a committed fixture once per test process."""
    from netwatch.baseline import load as load_baseline
    from netwatch.engine import analyze
    from netwatch.report import build_report

    baseline = load_baseline(FIXTURES / "baseline.json") if with_baseline else None
    result, alerts, statuses = analyze(
        [str(FIXTURES / f"{scenario}.pcap")], baseline=baseline, config={}
    )
    return build_report(
        result.index,
        alerts,
        statuses,
        capture_name=f"{scenario}.pcap",
        baseline=baseline,
    )


def alert_rules(report: dict) -> set[str]:
    return {alert["rule"] for alert in report["alerts"]}


def run_cli(*args: str, timeout: int = 120) -> subprocess.CompletedProcess:
    """Run the real entry point, the way a user would."""
    return subprocess.run(
        [sys.executable, "-m", "netwatch", *args],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def write_report(report: dict, path: Path) -> Path:
    path.write_text(json.dumps(report), encoding="utf-8")
    return path


def index_from_frames(frames) -> "TrafficIndex":
    """Build a traffic index from (ts_ns, frame) pairs, without touching disk."""
    from netwatch.flows import TrafficIndex
    from netwatch.packets import decode
    from netwatch.pcap import CapturePacket

    index = TrafficIndex()
    for position, (ts_ns, frame) in enumerate(frames):
        index.add(
            decode(
                CapturePacket(
                    index=position,
                    ts_ns=ts_ns,
                    data=frame,
                    orig_len=len(frame),
                    linktype=1,
                )
            )
        )
    return index


def rules_for(index, *, config=None, baseline=None):
    """Run the rule set against an index, returning (alerts, statuses)."""
    from netwatch.rules import run_rules

    return run_rules(index, config=config or {}, baseline=baseline)


def report_from_frames(frames, *, config=None, baseline=None) -> dict:
    from netwatch.report import build_report

    index = index_from_frames(frames)
    alerts, statuses = rules_for(index, config=config, baseline=baseline)
    return build_report(index, alerts, statuses, capture_name="synthetic", baseline=baseline)

